-- 1) Links do portal (um por transportadora) ------------------------------
create table if not exists public.portal_tokens (
  token             uuid primary key default gen_random_uuid(),
  transportadora_id text not null unique,          -- id da transportadora (texto: funciona com uuid ou número)
  ativo             boolean not null default true,
  criado_por        text,
  created_at        timestamptz not null default now(),
  ultimo_acesso     timestamptz
);
alter table public.portal_tokens enable row level security;
drop policy if exists "portal: admin" on public.portal_tokens;
create policy "portal: admin" on public.portal_tokens for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- 2) Ocorrências de entrega (do portal ou lançadas internamente) -----------
create table if not exists public.ocorrencias (
  id            uuid primary key default gen_random_uuid(),
  entrega_id    text not null,
  codigo        text not null,          -- coletado, agendado, entregue, cliente_ausente, recusa, avaria, endereco, reentrega, outro
  descricao     text,
  data_ocorrencia date not null default current_date,
  nova_previsao date,
  observacao    text,
  canhoto_path  text,                    -- arquivo no Storage (bucket "canhotos")
  origem        text not null default 'interno' check (origem in ('portal','interno')),
  autor         text,
  created_at    timestamptz not null default now()
);
create index if not exists ocorrencias_entrega_idx on public.ocorrencias (entrega_id);
alter table public.ocorrencias enable row level security;
drop policy if exists "ocorrencias: ler" on public.ocorrencias;
drop policy if exists "ocorrencias: lancar (admin)" on public.ocorrencias;
drop policy if exists "ocorrencias: excluir (admin)" on public.ocorrencias;
create policy "ocorrencias: ler" on public.ocorrencias for select to authenticated using (true);
create policy "ocorrencias: lancar (admin)" on public.ocorrencias for insert to authenticated with check (public.is_admin());
create policy "ocorrencias: excluir (admin)" on public.ocorrencias for delete to authenticated using (public.is_admin());

-- 3) Tabelas de frete (uma por transportadora × UF; uf = '*' vale para todas) ---
create table if not exists public.tabelas_frete (
  id                uuid primary key default gen_random_uuid(),
  transportadora_id text not null,
  uf                text not null default '*',
  nome              text,
  componentes       jsonb not null default '{}'::jsonb,  -- faixas de peso, ad valorem, GRIS, pedágio, taxas, mínimo, ICMS
  ativo             boolean not null default true,
  updated_at        timestamptz not null default now(),
  constraint tabelas_frete_unica unique (transportadora_id, uf)
);
alter table public.tabelas_frete enable row level security;
drop policy if exists "tabelas: ler" on public.tabelas_frete;
drop policy if exists "tabelas: gravar (admin)" on public.tabelas_frete;
create policy "tabelas: ler" on public.tabelas_frete for select to authenticated using (true);
create policy "tabelas: gravar (admin)" on public.tabelas_frete for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- 4) Romaneios de coleta --------------------------------------------------
create table if not exists public.romaneios (
  id                uuid primary key default gen_random_uuid(),
  numero            bigint generated by default as identity,
  transportadora_id text not null,
  entregas          text[] not null default '{}',
  motorista         text,
  placa             text,
  observacao        text,
  criado_por        text,
  created_at        timestamptz not null default now(),
  coletado_em       timestamptz
);
alter table public.romaneios enable row level security;
drop policy if exists "romaneios: ler" on public.romaneios;
drop policy if exists "romaneios: gravar (admin)" on public.romaneios;
drop policy if exists "romaneios: criar (logado)" on public.romaneios;
drop policy if exists "romaneios: excluir (admin)" on public.romaneios;
create policy "romaneios: ler" on public.romaneios for select to authenticated using (true);
-- a equipe da expedição (operadores) monta romaneios; excluir só administrador
create policy "romaneios: criar (logado)" on public.romaneios for insert to authenticated with check (true);
create policy "romaneios: excluir (admin)" on public.romaneios for delete to authenticated using (public.is_admin());

-- Confirmar coleta: operadores podem registrar SOMENTE a data de coleta (e o status
-- "Em Transporte") das NFs conferidas — sem poder editar o resto da entrega.
create or replace function public.registrar_coleta(p_ids text[], p_data date, p_romaneio uuid default null) returns integer
language plpgsql volatile security definer set search_path = public as $$
declare v_email text := coalesce(auth.jwt() ->> 'email', ''); v_n integer; v_nfs text;
begin
  if v_email = '' then raise exception 'Faça login.'; end if;
  if p_data is null or p_data > current_date or p_data < current_date - 30 then raise exception 'Data de coleta inválida.'; end if;
  with up as (
    update entregas set data_coleta = p_data,
      status = case when status in ('Pendente','Aguardando coleta','Frete Conferido') then 'Em Transporte' else status end
    where id::text = any(p_ids) and data_coleta is null
      and status not in ('Entregue','Devolvido','Devolução','Em devolução')
    returning nota_fiscal
  ) select count(*), string_agg(nota_fiscal, ', ') into v_n, v_nfs from up;
  if p_romaneio is not null then update romaneios set coletado_em = now() where id = p_romaneio; end if;
  if v_n > 0 then
    insert into logs_auditoria (usuario_email, acao, modulo, detalhes)
    values (v_email, 'EDITOU', 'ENTREGAS', format('Confirmou a coleta (%s) na Expedição: NF %s', to_char(p_data, 'DD/MM/YYYY'), v_nfs));
  end if;
  return v_n;
end $$;
revoke all on function public.registrar_coleta(text[], date, uuid) from public;
grant execute on function public.registrar_coleta(text[], date, uuid) to authenticated;

-- 5) Funções do portal (o transportador NÃO faz login) --------------------
-- Só funcionam com um link válido e só enxergam/alteram NFs da própria transportadora.
create or replace function public.portal_listar(p_token uuid) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v_transp text; v_nome text;
begin
  select transportadora_id into v_transp from portal_tokens where token = p_token and ativo;
  if v_transp is null then raise exception 'Link inválido ou desativado.'; end if;
  select nome into v_nome from transportadoras where id::text = v_transp;
  return jsonb_build_object(
    'transportadora', v_nome,
    'entregas', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', e.id::text, 'nf', e.nota_fiscal, 'cliente', c.nome, 'cidade', coalesce(e.cidade_destino, c.cidade), 'uf', coalesce(e.uf_destino, c.uf),
        'faturamento', e.data_faturamento, 'coleta', e.data_coleta, 'previsao', e.data_previsao,
        'agendamento', e.data_entrega_agendamento, 'status', e.status, 'volumes', e.volume, 'peso', e.peso_kg
      ) order by e.data_faturamento desc)
      from entregas e left join clientes c on c.id = e.cliente_id
      where e.transportadora_id::text = v_transp
        and e.status not in ('Entregue','Devolvido','Devolução','Em devolução')
        and coalesce(e.data_faturamento, current_date) >= current_date - 180
    ), '[]'::jsonb)
  );
end $$;

create or replace function public.portal_registrar(
  p_token uuid, p_entrega_id text, p_codigo text, p_data date,
  p_nova_previsao date default null, p_observacao text default null, p_canhoto text default null
) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare v_transp text; v_nome text; v_nf text; v_status text; v_desc text;
begin
  select transportadora_id into v_transp from portal_tokens where token = p_token and ativo;
  if v_transp is null then raise exception 'Link inválido ou desativado.'; end if;
  select nota_fiscal into v_nf from entregas where id::text = p_entrega_id and transportadora_id::text = v_transp;
  if v_nf is null then raise exception 'NF não encontrada para esta transportadora.'; end if;
  if p_data is null or p_data > current_date + 60 or p_data < current_date - 365 then raise exception 'Data inválida.'; end if;
  select nome into v_nome from transportadoras where id::text = v_transp;

  v_desc := case p_codigo
    when 'coletado' then 'Coletado / em trânsito'
    when 'agendado' then 'Entrega agendada'
    when 'entregue' then 'Entregue'
    when 'cliente_ausente' then 'Cliente ausente / fechado'
    when 'recusa' then 'Recusado pelo cliente'
    when 'avaria' then 'Avaria'
    when 'endereco' then 'Endereço não localizado'
    when 'reentrega' then 'Reentrega programada'
    when 'outro' then 'Outra ocorrência'
    else null end;
  if v_desc is null then raise exception 'Código de ocorrência inválido.'; end if;
  if p_codigo = 'entregue' and p_data > current_date then raise exception 'A data de entrega não pode ser futura.'; end if;

  insert into ocorrencias (entrega_id, codigo, descricao, data_ocorrencia, nova_previsao, observacao, canhoto_path, origem, autor)
  values (p_entrega_id, p_codigo, v_desc, p_data, p_nova_previsao, left(p_observacao, 500), p_canhoto, 'portal', v_nome);

  -- reflete no Painel de Entregas
  if p_codigo = 'entregue' then
    update entregas set status = 'Entregue', data_entrega_agendamento = p_data where id::text = p_entrega_id;
  elsif p_codigo = 'coletado' then
    update entregas set status = 'Em Transporte', data_coleta = coalesce(data_coleta, p_data),
      data_previsao = coalesce(p_nova_previsao, data_previsao) where id::text = p_entrega_id;
  elsif p_codigo = 'agendado' then
    update entregas set status = 'Agendado', data_entrega_agendamento = p_data where id::text = p_entrega_id;
  else
    update entregas set status = 'Problema', data_previsao = coalesce(p_nova_previsao, data_previsao) where id::text = p_entrega_id;
  end if;
  select status into v_status from entregas where id::text = p_entrega_id;

  update portal_tokens set ultimo_acesso = now() where token = p_token;
  insert into logs_auditoria (usuario_email, acao, modulo, detalhes)
  values ('portal: ' || coalesce(v_nome, v_transp), 'EDITOU', 'ENTREGAS',
          format('Ocorrência pelo portal da transportadora na NF %s: %s (%s)%s', v_nf, v_desc, to_char(p_data, 'DD/MM/YYYY'),
                 case when p_observacao is not null and p_observacao <> '' then ' — ' || left(p_observacao, 200) else '' end));
  return jsonb_build_object('ok', true, 'status', v_status);
end $$;

revoke all on function public.portal_listar(uuid) from public;
revoke all on function public.portal_registrar(uuid, text, text, date, date, text, text) from public;
grant execute on function public.portal_listar(uuid) to anon, authenticated;
grant execute on function public.portal_registrar(uuid, text, text, date, date, text, text) to anon, authenticated;

-- 6) Fotos dos canhotos (Supabase Storage) ---------------------------------
-- verifica o link sem expor a tabela de links
create or replace function public.portal_token_valido(p_token text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from portal_tokens where token::text = p_token and ativo);
$$;
grant execute on function public.portal_token_valido(text) to anon, authenticated;

-- O portal só consegue enviar arquivos para a pasta do próprio link; só usuários logados veem.
do $$
begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public) values ('canhotos', 'canhotos', false) on conflict (id) do nothing;
  end if;
end $$;

do $$
begin
  if to_regclass('storage.objects') is not null then
    execute 'drop policy if exists "canhotos: enviar pelo portal" on storage.objects';
    execute 'drop policy if exists "canhotos: ver (logado)" on storage.objects';
    execute 'drop policy if exists "canhotos: enviar (logado)" on storage.objects';
    execute $p$create policy "canhotos: enviar pelo portal" on storage.objects for insert to anon
      with check (bucket_id = 'canhotos' and public.portal_token_valido((storage.foldername(name))[1]))$p$;
    execute $p$create policy "canhotos: ver (logado)" on storage.objects for select to authenticated using (bucket_id = 'canhotos')$p$;
    execute $p$create policy "canhotos: enviar (logado)" on storage.objects for insert to authenticated with check (bucket_id = 'canhotos')$p$;
  end if;
end $$;

